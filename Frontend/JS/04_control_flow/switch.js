let month = 7
switch(month){
    case 1:
        console.log("January")
    break;    
    case 2:
        console.log("Febraury")
    break;    
    case 3:
        console.log("March")
    break;    
    case 4:
        console.log("April")
    break;    
    case 5:
        console.log("May")
    break;    
    case 6:
        console.log("June")
    break;  
    
    default:
        console.log(`Not from month 1-6 , month is ${month}`);
    break;    
        
}
